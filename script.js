let currentCase = null;
let currentRoles = [];
let timerInterval = null;

const switchScreen = (screenId) => {
    document.querySelectorAll('.phase').forEach(el => el.classList.remove('active'));
    document.getElementById(screenId).classList.add('active');
};

document.getElementById('generate-btn').addEventListener('click', () => {
    const count = parseInt(document.getElementById('player-count').value);
    if (count < 3 || count > 5) {
        document.getElementById('setup-error').classList.remove('hidden');
        return;
    }
    document.getElementById('setup-error').classList.add('hidden');

    currentCase = casesData[Math.floor(Math.random() * casesData.length)];
    currentRoles = currentCase.roles.slice(0, count);

    renderSimulationScreen();
    switchScreen('simulation-phase');
});

const renderSimulationScreen = () => {
    document.getElementById('case-title').innerText = currentCase.title;
    document.getElementById('case-text').innerText = currentCase.description;

    const rolesContainer = document.getElementById('roles-container');
    rolesContainer.innerHTML = '';

    currentRoles.forEach((role, index) => {
        // Використовуємо тег <details> для згортання/розгортання картки
        const roleHtml = `
            <details class="role-card">
                <summary>Гравець ${index + 1}: ${role.name}</summary>
                <div class="role-content">
                    <p><strong>Ціль ролі:</strong> ${role.desc}</p>
                    <br>
                    <strong>🎯 Бажані дії команди:</strong>
                    <ul class="goals-list">
                        ${role.goals.map(g => `<li>${g}</li>`).join('')}
                    </ul>
                    <strong>❌ Чого не можна допустити (Червоні лінії):</strong>
                    <ul class="redlines-list">
                        ${role.redLines.map(r => `<li>${r}</li>`).join('')}
                    </ul>
                </div>
            </details>
        `;
        rolesContainer.innerHTML += roleHtml;
    });
};

document.getElementById('start-timer-btn').addEventListener('click', (e) => {
    e.target.disabled = true;
    let timeRemaining = 720; // 12 хвилин обговорення
    timerInterval = setInterval(() => {
        if (timeRemaining > 0) {
            timeRemaining--;
            const mins = String(Math.floor(timeRemaining / 60)).padStart(2, '0');
            const secs = String(timeRemaining % 60).padStart(2, '0');
            document.getElementById('timer-display').innerText = `${mins}:${secs}`;
        } else {
            clearInterval(timerInterval);
            alert("Час вийшов! Переходимо до фіксації рішень.");
            prepareEvaluationScreen();
        }
    }, 1000);
});

document.getElementById('skip-timer-btn').addEventListener('click', () => {
    clearInterval(timerInterval);
    prepareEvaluationScreen();
});

const prepareEvaluationScreen = () => {
    const container = document.getElementById('evaluation-container');
    container.innerHTML = '';

    currentRoles.forEach((role, playerIndex) => {
        let html = `<div class="eval-player-section">
            <h3>Позиція: ${role.name}</h3>
            <div class="eval-group">
                <h4>Які з цих рішень команда ПОГОДИЛАСЬ виконати?</h4>`;
        
        role.goals.forEach(goal => {
            html += `<label class="checkbox-item goal-text">
                <input type="checkbox" class="goal-cb"> ${goal}
            </label>`;
        });

        html += `</div><div class="eval-group">
                <h4>Чи здійснила команда такі дії (порушення)?</h4>`;
        
        role.redLines.forEach(redline => {
            html += `<label class="checkbox-item redline-text">
                <input type="checkbox" class="redline-cb"> ${redline}
            </label>`;
        });

        html += `</div></div>`;
        container.innerHTML += html;
    });

    switchScreen('evaluation-phase');
};

document.getElementById('calculate-btn').addEventListener('click', () => {
    const achievedGoals = document.querySelectorAll('.goal-cb:checked').length;
    const totalGoals = document.querySelectorAll('.goal-cb').length;
    const crossedRedLines = document.querySelectorAll('.redline-cb:checked').length;

    const scoreDisplay = document.getElementById('final-score-display');
    let verdict = "";
    let verdictClass = "";

    // Оцінювання на основі червоних ліній (якщо є хоча б 1 — це провал)
    if (crossedRedLines > 0) {
        verdict = "❌ Провал (Перетнуто червоні лінії).";
        verdictClass = "verdict-fail";
        scoreDisplay.innerHTML = `<h3 class="${verdictClass}">${verdict}</h3>
        <p>Рішення команди містить юридично неприпустимі або катастрофічні для бізнесу дії. Жодні позитивні кроки не можуть виправдати порушення закону чи критичної безпеки.</p>`;
    } else if (achievedGoals >= Math.ceil(totalGoals * 0.6)) {
        verdict = "✅ Збалансоване партнерське рішення.";
        verdictClass = "verdict-success";
        scoreDisplay.innerHTML = `<h3 class="${verdictClass}">${verdict}</h3>
        <p>Команда знайшла відмінний компроміс! Бізнес продовжує роботу, ризики мінімізовані, а закон не порушено. Досягнуто ${achievedGoals} з ${totalGoals} корисних цілей.</p>`;
    } else {
        verdict = "⚠️ Дисбаланс або слабке рішення.";
        verdictClass = "verdict-neutral";
        scoreDisplay.innerHTML = `<h3 class="${verdictClass}">${verdict}</h3>
        <p>Компанія вижила, і критичних помилок не зроблено. Але команда відкинула забагато корисних кроків (виконано лише ${achievedGoals} з ${totalGoals} цілей). Хтось пішов на надмірні поступки.</p>`;
    }

    // Виведення Debrief (Розбору)
    const debriefList = document.getElementById('debrief-list');
    debriefList.innerHTML = currentCase.debrief.map(item => `<li>${item}</li>`).join('');

    switchScreen('result-phase');
});

